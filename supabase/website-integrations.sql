-- Install after workspaces.sql and organization-profiles.sql.
begin;
create table if not exists public.workspace_api_settings (
  workspace_id uuid primary key references public.workspaces(id) on delete cascade,
  enabled boolean not null default true, external_enabled boolean not null default true,
  monthly_limit integer not null default 1000 check(monthly_limit between 1 and 10000000),
  minute_limit integer not null default 30 check(minute_limit between 1 and 10000),
  retention_days integer not null default 30 check(retention_days between 7 and 365)
);
alter table public.workspace_api_settings add column if not exists knowledge_revision bigint not null default 1;
insert into workspace_api_settings(workspace_id) select id from workspaces on conflict do nothing;
create table if not exists public.website_integrations (
  id uuid primary key default gen_random_uuid(), workspace_id uuid not null references public.workspaces(id) on delete cascade,
  name text not null check(length(name) between 1 and 80), site_origin text not null,
  enabled boolean not null default true, created_at timestamptz not null default now(),
  created_by uuid references public.users(id) on delete set null
);
create table if not exists public.persona_api_keys (
  id uuid primary key default gen_random_uuid(), integration_id uuid not null references public.website_integrations(id) on delete cascade,
  key_hash text not null unique check(length(key_hash)=64), prefix text not null,
  scope text not null default 'persona:chat' check(scope='persona:chat'),
  expires_at timestamptz not null default now()+interval '90 days', revoked_at timestamptz,
  created_at timestamptz not null default now(), created_by uuid references public.users(id) on delete set null
);
create table if not exists public.persona_sessions (
  id uuid primary key default gen_random_uuid(), integration_id uuid not null references public.website_integrations(id) on delete cascade,
  created_at timestamptz not null default now(), expires_at timestamptz not null default now()+interval '24 hours'
);
create index if not exists persona_sessions_integration on persona_sessions(integration_id,created_at);
create table if not exists public.persona_requests (
  id uuid primary key default gen_random_uuid(), workspace_id uuid not null references public.workspaces(id) on delete cascade,
  key_id uuid references public.persona_api_keys(id) on delete set null,
  integration_id uuid references public.website_integrations(id) on delete set null,
  principal text not null, source text not null check(source in('own_platform','external_api')),
  request_key text not null check(length(request_key) between 1 and 100), message_hash text not null,
  session_id uuid references public.persona_sessions(id) on delete set null,
  state text not null default 'pending' check(state in('pending','complete','failed')),
  lease uuid not null default gen_random_uuid(), created_at timestamptz not null default now(), completed_at timestamptz,
  response_status integer, response jsonb, input_tokens integer, output_tokens integer
);
create unique index if not exists persona_requests_idempotency on persona_requests(workspace_id,principal,request_key);
create index if not exists persona_requests_usage on persona_requests(workspace_id,created_at);
alter table public.persona_requests add column if not exists knowledge_stamp text;
create table if not exists public.workspace_audit (
  id bigint generated by default as identity primary key,
  workspace_id uuid references public.workspaces(id) on delete cascade, actor_id uuid references public.users(id) on delete set null,
  action text not null, detail jsonb not null default '{}', created_at timestamptz not null default now()
);
create index if not exists workspace_audit_workspace on workspace_audit(workspace_id,created_at);

create or replace function public.persona_knowledge_stamp(p_workspace uuid) returns text
language plpgsql set search_path=public as $$
declare stamp text; tab text; sources text;
begin
  select knowledge_revision::text into stamp from workspace_api_settings where workspace_id=p_workspace;
  foreach tab in array array['files','posts'] loop
    if to_regclass('public.'||tab) is null then continue; end if;
    execute format('select string_agg(id::text,'','' order by id) from public.%I t where to_jsonb(t)->>''workspace_id''=$1::text
      and coalesce(to_jsonb(t)->>''status'',''published'')=''published''
      and coalesce(to_jsonb(t)->>''audience'',''public'')=''public''
      and (to_jsonb(t)->>''valid_from'' is null or (to_jsonb(t)->>''valid_from'')::timestamptz<=now())
      and (to_jsonb(t)->>''valid_until'' is null or (to_jsonb(t)->>''valid_until'')::timestamptz>now())',tab) into sources using p_workspace;
    stamp:=coalesce(stamp,'1')||':'||coalesce(sources,'');
  end loop;
  return md5(stamp);
end $$;
create or replace function public.bump_persona_knowledge() returns trigger
language plpgsql set search_path=public as $$
declare target uuid;
begin
  if tg_op='UPDATE' and (to_jsonb(new)-'views'-'updated_at')=(to_jsonb(old)-'views'-'updated_at') then return null; end if;
  target:=case when tg_op='DELETE' then old.workspace_id else new.workspace_id end;
  if target is null or not exists(select 1 from workspaces where id=target) then return null; end if;
  insert into workspace_api_settings(workspace_id,knowledge_revision) values(target,2)
    on conflict(workspace_id) do update set knowledge_revision=workspace_api_settings.knowledge_revision+1;
  return null;
end $$;
do $$ declare tab text; begin
  foreach tab in array array['files','posts','profiles'] loop
    if to_regclass('public.'||tab) is null then continue; end if;
    execute format('drop trigger if exists persona_knowledge_changed on public.%I',tab);
    execute format('create trigger persona_knowledge_changed after insert or update or delete on public.%I for each row execute function bump_persona_knowledge()',tab);
  end loop;
end $$;
create or replace function public.reserve_persona_request(p_workspace uuid,p_key uuid,p_source text,p_request text,p_hash text,p_session uuid)
returns jsonb language plpgsql set search_path=public as $$
declare w workspaces; settings workspace_api_settings; k persona_api_keys; site website_integrations;
  existing persona_requests; created persona_requests; principal_id text; usage_count bigint; stamp text;
begin
  select * into w from workspaces where id=p_workspace for update;
  if w.id is null or w.status<>'active' then raise exception 'Workspace is unavailable.'; end if;
  insert into workspace_api_settings(workspace_id) values(w.id) on conflict do nothing;
  select * into settings from workspace_api_settings where workspace_id=w.id;
  if not settings.enabled then raise exception 'Persona access is disabled.'; end if;
  if p_source='external_api' then
    if not settings.external_enabled then raise exception 'External access is disabled.'; end if;
    select * into k from persona_api_keys where id=p_key for share;
    select * into site from website_integrations where id=k.integration_id for share;
    if k.id is null or k.revoked_at is not null or k.expires_at<=now() or site.workspace_id<>w.id or not site.enabled then
      raise exception 'API credential is unavailable.';
    end if;
    if p_session is not null and not exists(select 1 from persona_sessions where id=p_session and integration_id=site.id and expires_at>now()) then
      raise exception 'This chat session is unavailable.';
    end if;
    principal_id:=site.id::text;
  elsif p_source='own_platform' and p_key is null and p_session is null then principal_id:='platform';
  else raise exception 'Invalid request source.'; end if;
  if p_request is null or length(p_request) not between 1 and 100 or p_hash is null then raise exception 'Invalid request identity.'; end if;
  stamp:=persona_knowledge_stamp(w.id);
  select * into existing from persona_requests where workspace_id=w.id and principal=principal_id and request_key=p_request;
  if existing.id is not null then
    if existing.message_hash<>p_hash or existing.session_id is distinct from p_session then raise exception 'Request ID was used for a different message.'; end if;
    if existing.knowledge_stamp is distinct from stamp then return jsonb_build_object('state','obsolete'); end if;
    if existing.state='pending' and existing.created_at<now()-interval '50 seconds' then
      update persona_requests set state='failed',response_status=503,response='{"error":"The previous request timed out. Send a new request ID to try again."}',completed_at=now() where id=existing.id returning * into existing;
    end if;
    return jsonb_build_object('state',existing.state,'id',existing.id,'response',existing.response,'status',existing.response_status);
  end if;
  select count(*) into usage_count from persona_requests where workspace_id=w.id and created_at>=date_trunc('month',now());
  if usage_count>=settings.monthly_limit then raise exception 'Workspace monthly request limit reached.'; end if;
  select count(*) into usage_count from persona_requests where workspace_id=w.id and created_at>now()-interval '1 minute';
  if usage_count>=settings.minute_limit then raise exception 'Too many requests. Try again in a minute.'; end if;
  insert into persona_requests(workspace_id,key_id,integration_id,principal,source,request_key,message_hash,session_id,knowledge_stamp)
    values(w.id,k.id,site.id,principal_id,p_source,p_request,p_hash,p_session,stamp) returning * into created;
  return jsonb_build_object('state','reserved','id',created.id,'lease',created.lease);
end $$;
create or replace function public.finish_persona_request(p_id uuid,p_lease uuid,p_status integer,p_response jsonb,p_input integer,p_output integer)
returns boolean language plpgsql set search_path=public as $$
begin
  update persona_requests set state=case when p_status between 200 and 299 then 'complete' else 'failed' end,
    response_status=p_status,response=p_response,completed_at=now(),input_tokens=p_input,output_tokens=p_output
    where id=p_id and lease=p_lease and state='pending';
  return found;
end $$;
create or replace function public.create_persona_session(p_key uuid) returns jsonb
language plpgsql set search_path=public as $$
declare k persona_api_keys; site website_integrations; w workspaces; settings workspace_api_settings; created persona_sessions;
begin
  select i.* into site from website_integrations i join persona_api_keys a on a.integration_id=i.id where a.id=p_key;
  select * into w from workspaces where id=site.workspace_id for update;
  select * into k from persona_api_keys where id=p_key for share;
  select * into site from website_integrations where id=k.integration_id for share;
  select * into settings from workspace_api_settings where workspace_id=w.id;
  if w.id is null or w.status<>'active' or not coalesce(settings.enabled,true) or not coalesce(settings.external_enabled,true) or
    k.revoked_at is not null or k.expires_at<=now() or not site.enabled then raise exception 'API credential is unavailable.'; end if;
  if (select count(*) from persona_sessions where integration_id=site.id and created_at>now()-interval '1 minute')>=30 then
    raise exception 'Too many sessions. Try again in a minute.'; end if;
  insert into persona_sessions(integration_id) values(site.id) returning * into created;
  return jsonb_build_object('sessionId',created.id,'expiresAt',created.expires_at);
end $$;
create or replace function public.manage_persona_integration(p_actor uuid,p_workspace uuid,p_action text,p_input jsonb)
returns jsonb language plpgsql set search_path=public as $$
declare w workspaces; site website_integrations; new_key persona_api_keys; target uuid;
begin
  select * into w from workspaces where id=p_workspace and status='active' for update;
  if w.id is null or not exists(select 1 from workspace_members where workspace_id=w.id and user_id=p_actor and status='active' and role in('owner','admin')) then
    raise exception 'Workspace administrator access is required.'; end if;
  if p_action='create' then
    if (select count(*) from website_integrations where workspace_id=w.id)>=10 then raise exception 'Ten website connections are already configured.'; end if;
    if coalesce(length(p_input->>'name'),0) not between 1 and 80 or coalesce(p_input->>'origin','') not like 'https://%' then raise exception 'Name and HTTPS website are required.'; end if;
    insert into website_integrations(workspace_id,name,site_origin,created_by) values(w.id,p_input->>'name',p_input->>'origin',p_actor) returning * into site;
  else
    target:=(p_input->>'id')::uuid;
    select * into site from website_integrations where id=target and workspace_id=w.id for update;
    if site.id is null then raise exception 'Website connection is unavailable.'; end if;
  end if;
  if p_action in('create','rotate') then
    if p_action='rotate' then update persona_api_keys set revoked_at=now() where integration_id=site.id and revoked_at is null; end if;
    insert into persona_api_keys(integration_id,key_hash,prefix,created_by) values(site.id,p_input->>'hash',p_input->>'prefix',p_actor) returning * into new_key;
  elsif p_action='revoke' then
    update persona_api_keys set revoked_at=now() where integration_id=site.id and revoked_at is null;
  elsif p_action='toggle' then
    if jsonb_typeof(p_input->'enabled') is distinct from 'boolean' then raise exception 'Choose enable or disable.'; end if;
    update website_integrations set enabled=(p_input->>'enabled')::boolean where id=site.id returning * into site;
  else raise exception 'Invalid integration action.'; end if;
  insert into workspace_audit(workspace_id,actor_id,action,detail) values(w.id,p_actor,'integration.'||p_action,jsonb_build_object('integrationId',site.id));
  return jsonb_build_object('integrationId',site.id,'keyId',new_key.id);
end $$;
create or replace function public.persona_usage(p_workspace uuid) returns jsonb
language sql set search_path=public as $$
  select jsonb_build_object('month',date_trunc('month',now()),'requests',count(*),
    'platform',count(*) filter(where source='own_platform'),'external',count(*) filter(where source='external_api'),
    'failed',count(*) filter(where state='failed'),'pending',count(*) filter(where state='pending'),
    'inputTokens',sum(input_tokens),'outputTokens',sum(output_tokens))
  from persona_requests where workspace_id=p_workspace and created_at>=date_trunc('month',now())
$$;
do $$ declare t text; begin
  foreach t in array array['workspace_api_settings','website_integrations','persona_api_keys','persona_sessions','persona_requests','workspace_audit'] loop
    execute format('alter table public.%I enable row level security',t);
    execute format('grant all on public.%I to service_role',t);
  end loop;
end $$;
grant usage,select on sequence public.workspace_audit_id_seq to service_role;
revoke all on function public.reserve_persona_request(uuid,uuid,text,text,text,uuid) from public;
revoke all on function public.finish_persona_request(uuid,uuid,integer,jsonb,integer,integer) from public;
revoke all on function public.create_persona_session(uuid) from public;
grant execute on function public.reserve_persona_request(uuid,uuid,text,text,text,uuid),public.finish_persona_request(uuid,uuid,integer,jsonb,integer,integer),public.create_persona_session(uuid) to service_role;
revoke all on function public.manage_persona_integration(uuid,uuid,text,jsonb),public.persona_usage(uuid) from public;
revoke all on function public.persona_knowledge_stamp(uuid),public.bump_persona_knowledge() from public;
grant execute on function public.persona_knowledge_stamp(uuid) to service_role;
grant execute on function public.manage_persona_integration(uuid,uuid,text,jsonb),public.persona_usage(uuid) to service_role;
commit;
