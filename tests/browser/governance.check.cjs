async (page) => {
  const base = 'http://127.0.0.1:5179/tests/browser/governance.html';
  const results = [];
  const check = (value, message) => { if (!value) throw new Error(message); };
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto(`${base}?role=owner&view=/superadmin/customers`);
  const maya = page.getByRole('row').filter({ hasText: 'maya@example.test' });
  await maya.getByRole('button', { name: 'Edit & tags', exact: true }).click();
  await page.getByRole('checkbox', { name: /Private profile/ }).check();
  await page.getByRole('button', { name: 'Save changes', exact: true }).click();
  await page.getByText('Customer account updated.', { exact: true }).waitFor();
  check((await maya.innerText()).includes('Private profile'), 'Customer tag was not saved');
  results.push('Customer tags save');
  await page.getByRole('link', { name: 'Invite links', exact: true }).first().click();
  await page.getByRole('textbox', { name: 'Recipient or note' }).fill('New creator');
  await page.getByRole('button', { name: 'Create invite link', exact: true }).click();
  await page.getByRole('textbox', { name: 'Invite link', exact: true }).waitFor();
  check((await page.getByRole('textbox', { name: 'Invite link', exact: true }).inputValue()).endsWith('/invite/NEWI2345'), 'Incorrect invitation URL');
  check((await page.locator('body').innerText()).includes('Dev Kumar'), 'Invited member attribution missing');
  results.push('Invite creation and attribution');
  await page.getByRole('link', { name: 'Suggestions', exact: true }).first().click();
  const suggestion = page.locator('article').filter({ hasText: 'Search profiles by tags' });
  check(await page.getByRole('button', { name: 'Send suggestion', exact: true }).count() === 0, 'Owner received suggestion submission controls');
  await suggestion.getByRole('combobox', { name: /^Status/ }).selectOption('planned');
  await suggestion.getByRole('textbox', { name: 'Reply to admin' }).fill('We will add tag search.');
  await suggestion.getByRole('button', { name: 'Save response' }).click();
  await page.waitForFunction(() => window.governanceFixture.suggestions[0].status === 'planned');
  check(await page.evaluate(() => window.governanceFixture.suggestions[0].owner_reply === 'We will add tag search.'), 'Owner response was not saved');
  results.push('SuperAdmin suggestion review');
  await page.goto(`${base}?role=owner&view=/admin/settings`);
  await page.getByRole('heading', { name: 'SuperAdmin dashboard', exact: true }).waitFor();
  check(await page.evaluate(() => window.governanceFixture.personalReads.length === 0), 'Owner triggered personal Studio data reads');
  check(await page.getByRole('link', { name: 'My Studio', exact: true }).count() === 0, 'Owner still has personal Studio navigation');
  results.push('Exclusive SuperAdmin account and redirect');
  await page.getByRole('link', { name: 'Sales & payments', exact: true }).first().click();
  await page.getByRole('heading', { name: 'Sales & payments', exact: true }).waitFor();
  check(await page.getByRole('heading', { name: 'INR', exact: true }).count() === 1, 'INR total missing');
  check(await page.getByRole('heading', { name: 'USD', exact: true }).count() === 1, 'USD total missing');
  await page.getByRole('button', { name: 'Pause checkout for Maya Patel', exact: true }).click();
  await page.getByRole('button', { name: 'Enable checkout for Maya Patel', exact: true }).waitFor();
  check(await page.evaluate(() => !window.governanceFixture.sales.admins[0].checkoutEnabled), 'Checkout pause did not save');
  results.push('Currency-separated earnings and checkout management');
  await page.getByRole('link', { name: 'Main site settings', exact: true }).first().click();
  await page.getByRole('heading', { name: 'Main site settings', exact: true }).waitFor();
  await page.getByRole('textbox', { name: 'Site name', exact: true }).fill('Creator community');
  await page.getByRole('textbox', { name: 'Headline opening', exact: true }).fill('Find your');
  await page.getByRole('textbox', { name: 'Highlighted words', exact: true }).fill('next');
  await page.getByRole('textbox', { name: 'Headline ending', exact: true }).fill('mentor');
  await page.getByRole('checkbox', { name: 'Show products and offerings', exact: true }).uncheck();
  await page.getByRole('button', { name: 'Save main site settings', exact: true }).click();
  await page.getByText('Main site settings saved. The public directory now uses these settings.', { exact: true }).waitFor();
  await page.getByRole('link', { name: 'Main site', exact: true }).click();
  await page.getByRole('heading', { name: 'Find your next mentor', exact: true }).waitFor();
  check(await page.getByRole('link', { name: 'Creator community home', exact: true }).count() === 1, 'Brand setting missing');
  check(await page.locator('.directory-products').count() === 0, 'Hidden product section still renders');
  check(await page.getByText('Ravi', { exact: true }).count() === 0, 'SuperAdmin appeared in the profile directory');
  results.push('Main site settings save and public rendering');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(`${base}?role=member&view=/admin/suggestions`);
  await page.getByRole('heading', { name: 'Platform suggestions', exact: true }).waitFor();
  check(await page.getByRole('button', { name: 'Save response', exact: true }).count() === 0, 'Member received owner controls');
  await page.getByRole('textbox', { name: 'Title', exact: true }).fill('Simpler invites');
  await page.getByRole('textbox', { name: 'Description', exact: true }).fill('Explain invitation links more clearly.');
  await page.getByRole('button', { name: 'Send suggestion' }).click();
  await page.getByRole('heading', { name: 'Simpler invites', exact: true }).waitFor();
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile suggestion page overflows');
  results.push('Member suggestions on mobile');
  await page.goto(`${base}?role=member&view=/`);
  await page.getByRole('button', { name: 'Account options', exact: true }).waitFor();
  check(await page.getByText('Ananya Rao', { exact: true }).count() === 0, 'Private member appeared in directory');
  await page.getByRole('button', { name: 'Account options', exact: true }).click();
  await page.getByRole('link', { name: 'Dashboard', exact: true }).waitFor();
  await page.keyboard.press('Escape');
  check(!(await page.getByRole('link', { name: 'Dashboard', exact: true }).isVisible()), 'Escape did not close the account menu');
  await page.evaluate(() => { window.governanceFixture.failLogout = true; });
  await page.getByRole('button', { name: 'Account options', exact: true }).click();
  await page.getByRole('button', { name: 'Logout', exact: true }).click();
  await page.getByText('Could not log out. Please try again.', { exact: true }).waitFor();
  await page.evaluate(() => { window.governanceFixture.failLogout = false; });
  await page.getByRole('button', { name: 'Logout', exact: true }).click();
  await page.getByRole('link', { name: 'Login', exact: true }).waitFor();
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile directory overflows');
  results.push('Account dropdown, keyboard dismissal, logout retry and Login');
  await page.goto(`${base}?role=visitor&view=/p/maya/home`);
  await page.getByRole('link', { name: 'Contact', exact: true }).waitFor();
  check(await page.getByText('Work with me', { exact: true }).count() === 0, 'Repeated contact CTA remains');
  check(await page.getByText('Let’s Connect', { exact: true }).count() === 0, 'Header contact CTA remains');
  await page.getByRole('link', { name: 'Contact', exact: true }).click();
  await page.getByRole('heading', { name: 'Contact Maya', exact: true }).waitFor();
  results.push('Contact page preserved without repeated buttons');
  return results;
}
