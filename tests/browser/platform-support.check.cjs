async page => {
  const base = 'http://127.0.0.1:5179/tests/browser/governance.html';
  const check = (value, message) => { if (!value) throw new Error(message); };
  const results = [];
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto(`${base}?role=member&view=/admin/support&no-profile=1`);
  await page.getByRole('heading', { name: 'Support', exact: true }).waitFor();
  const settings = page.getByRole('navigation', { name: 'Settings pages', exact: true });
  await settings.getByRole('link', { name: 'Support', exact: true }).waitFor();
  check(await page.getByRole('link', { name: 'Invite', exact: true }).count() === 1, 'Invite label missing');
  check(await page.getByRole('link', { name: 'Community', exact: true }).count() === 0, 'Community label remains');
  await page.getByRole('button', { name: 'New support request', exact: true }).click();
  await page.getByRole('textbox', { name: 'Subject', exact: true }).fill('Cannot publish my profile');
  await page.getByRole('textbox', { name: 'Describe the issue', exact: true }).fill('The publish button reports an error.');
  await page.evaluate(() => { window.governanceFixture.failSupportList = true; });
  await page.getByRole('button', { name: 'Refresh', exact: true }).click();
  await page.getByRole('alert').getByText('Support refresh unavailable.', { exact: true }).waitFor();
  check(await page.getByRole('textbox', { name: 'Subject', exact: true }).inputValue() === 'Cannot publish my profile', 'Refresh failure lost the request draft');
  await page.evaluate(() => { window.governanceFixture.failSupportList = false; });
  await page.getByRole('button', { name: 'Send request', exact: true }).click();
  await page.getByRole('heading', { name: 'Cannot publish my profile', exact: true }).waitFor();
  results.push('Settings Support is usable before profile setup and creates a threaded request');
  await page.goto(`${base}?role=member&view=/admin/support/1`);
  await page.getByText('Your payment has been confirmed.', { exact: true }).waitFor();
  await page.getByRole('textbox', { name: 'Your reply', exact: true }).fill('I still need the receipt.');
  await page.evaluate(() => { window.governanceFixture.failSupportReply = true; });
  await page.getByRole('button', { name: 'Send reply', exact: true }).click();
  await page.getByRole('alert').getByText('Support temporarily unavailable. Try again.', { exact: true }).waitFor();
  check(await page.getByRole('textbox', { name: 'Your reply', exact: true }).inputValue() === 'I still need the receipt.', 'Failed reply lost its draft');
  await page.evaluate(() => { window.governanceFixture.failSupportReply = false; });
  await page.getByRole('button', { name: 'Send reply', exact: true }).click();
  await page.getByText('I still need the receipt.', { exact: true }).waitFor();
  check(await page.evaluate(() => window.governanceFixture.supportTickets[0].status) === 'open', 'Member reply did not reopen request');
  check(await page.getByRole('combobox', { name: 'Request status', exact: true }).count() === 0, 'Member has owner status controls');
  results.push('Reply history, draft-preserving failure/retry and resolved-request reopening');
  await page.goto(`${base}?role=member&view=/admin/support`);
  await page.getByRole('button', { name: 'New support request', exact: true }).click();
  await page.getByRole('textbox', { name: 'Subject', exact: true }).fill('Delayed request');
  await page.getByRole('textbox', { name: 'Describe the issue', exact: true }).fill('This request finishes after I leave.');
  await page.evaluate(() => { window.governanceFixture.delaySupportCreate = true; });
  await page.getByRole('button', { name: 'Send request', exact: true }).click();
  await page.waitForFunction(() => !!window.governanceFixture.finishSupportCreate);
  check(await page.getByRole('button', { name: 'Cancel new request', exact: true }).isDisabled(), 'Pending request can be cancelled');
  await page.getByRole('link', { name: 'Invite', exact: true }).click();
  await page.getByRole('heading', { name: 'Invite links', exact: true }).waitFor();
  await page.evaluate(() => { window.governanceFixture.finishSupportCreate(); });
  await page.waitForFunction(() => window.governanceFixture.supportTickets.some(ticket => ticket.title === 'Delayed request'));
  await page.getByRole('heading', { name: 'Invite links', exact: true }).waitFor();
  check(await page.getByRole('heading', { name: 'Delayed request', exact: true }).count() === 0, 'Late creation redirected after leaving');
  results.push('Refresh preserves drafts and delayed creation respects navigation');
  await page.goto(`${base}?view=/superadmin/support`);
  await page.getByRole('heading', { name: 'Support inbox', exact: true }).waitFor();
  check(await page.getByRole('button', { name: 'New support request', exact: true }).count() === 0, 'Owner has customer submission form');
  await page.getByRole('link', { name: 'Payment confirmation', exact: true }).click();
  await page.getByRole('textbox', { name: 'Your reply', exact: true }).fill('The receipt is available in Orders.');
  await page.getByRole('combobox', { name: 'Request status', exact: true }).selectOption('in_progress');
  await page.getByRole('button', { name: 'Save response', exact: true }).click();
  await page.getByText('The receipt is available in Orders.', { exact: true }).waitFor();
  check(await page.evaluate(() => window.governanceFixture.supportTickets[0].status) === 'in_progress', 'Owner status was not saved');
  await page.getByRole('combobox', { name: 'Request status', exact: true }).selectOption('resolved');
  await page.getByRole('button', { name: 'Save response', exact: true }).click();
  await page.waitForFunction(() => window.governanceFixture.supportMessages.some(message => message.body === '' && message.status === 'resolved'));
  results.push('Exclusive owner inbox with replies and recorded status-only updates');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(`${base}?role=member&view=/admin/support`);
  await page.getByRole('heading', { name: 'Support', exact: true }).waitFor();
  await page.getByRole('button', { name: 'New support request', exact: true }).click();
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile support request form overflows');
  await page.goto(`${base}?role=member&view=/admin/support/1`);
  await page.getByRole('heading', { name: 'Payment confirmation', exact: true }).waitFor();
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile support conversation overflows');
  results.push('Mobile request list, form and conversation fit the viewport');
  return results;
}
