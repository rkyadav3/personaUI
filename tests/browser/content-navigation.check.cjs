async page => {
  const base = 'http://127.0.0.1:5179/tests/browser/admin-workflow.html';
  const check = (value, message) => { if (!value) throw new Error(message); };
  const results = [];
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto(`${base}?route=${encodeURIComponent('/admin/writing?tab=posts')}`);
  await page.getByRole('heading', { name: 'Content', exact: true }).waitFor();
  const tabs = page.getByRole('navigation', { name: 'Content sections', exact: true });
  await tabs.getByRole('link', { name: 'Templates', exact: true }).click();
  await page.getByRole('heading', { name: 'Create New Template', exact: true }).waitFor();
  await tabs.getByRole('link', { name: 'Research topics', exact: true }).click();
  await page.getByRole('heading', { name: 'Create New Topic', exact: true }).waitFor();
  await page.getByRole('textbox', { name: 'Topic Name', exact: true }).fill('Navigation research');
  await page.getByRole('button', { name: 'Create topic', exact: true }).click();
  await page.getByText('Topic created. Assign it to a file or article to start organizing.', { exact: true }).waitFor();
  await tabs.getByRole('link', { name: 'Articles', exact: true }).click();
  await page.getByRole('option', { name: 'Navigation research', exact: true }).waitFor({ state: 'attached' });
  results.push('One Content workspace with working article/template/topic navigation and fresh topic options');
  await page.getByRole('link', { name: 'Settings', exact: true }).click();
  const settings = page.getByRole('navigation', { name: 'Settings pages', exact: true });
  check(await settings.getByRole('link', { name: 'Invite links', exact: true }).count() === 0, 'Invites remain in Settings');
  check(await settings.getByRole('link', { name: 'Suggestions', exact: true }).count() === 0, 'Suggestions remain in Settings');
  await page.getByRole('link', { name: 'Community', exact: true }).click();
  const community = page.getByRole('navigation', { name: 'Community pages', exact: true });
  await community.getByRole('link', { name: 'Suggestions', exact: true }).waitFor();
  await page.getByRole('heading', { name: 'Invite links', exact: true }).waitFor();
  await page.getByRole('heading', { name: 'Your invite links', exact: true }).waitFor();
  check(await page.getByText(/Fixture does not support/).count() === 0, 'Invite destination failed to load');
  await community.getByRole('link', { name: 'Suggestions', exact: true }).click();
  await page.getByRole('heading', { name: 'Platform suggestions', exact: true }).waitFor();
  await page.getByRole('heading', { name: 'Suggest an improvement', exact: true }).waitFor();
  check(await page.getByText(/Fixture does not support/).count() === 0, 'Suggestions destination failed to load');
  results.push('Invites and Suggestions moved from Settings to Community');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(`${base}?route=${encodeURIComponent('/admin/writing?tab=topics')}`);
  await page.getByRole('heading', { name: 'Research topics', exact: true }).waitFor();
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile Content workspace overflows');
  await page.getByRole('navigation', { name: 'Content sections', exact: true }).getByRole('link', { name: 'Templates', exact: true }).click();
  await page.getByRole('heading', { name: 'Create New Template', exact: true }).waitFor();
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile template editor overflows');
  results.push('Mobile Content tabs and template layout');
  return results;
}
